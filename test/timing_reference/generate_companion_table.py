"""Run the pinned SX126x LoRa calculator body with the sensor's actual policy.
No hardware HAL or substitute LoRa formula: extract the dependency source verbatim.
"""
from pathlib import Path
import subprocess
import tempfile
import sys

root = Path(__file__).resolve().parents[2]
radio = root / '.pio/libdeps/Xiao_nrf52_bme680_sensor/RadioLib/src/modules/SX126x/SX126x.cpp'
source = radio.read_text()
start = source.index('    case RADIOLIB_MODEM_LORA: {', source.index('SX126x::calculateTimeOnAir'))
end = source.index('    case RADIOLIB_MODEM_FSK:', start)
body = source[start:end].removeprefix('    case RADIOLIB_MODEM_LORA: {')
body = body[:body.rfind('}')]
program = r'''
#include <stdint.h>
#include <cstdio>
#include "TraceTransactionBudget.h"
struct Data { struct { uint8_t spreadingFactor; float bandwidth; uint8_t codingRate; } lora; };
struct Config { struct { bool ldrOptimize,implicitHeader,crcEnabled; uint16_t preambleLength; } lora; };
uint32_t reference(Data dr,Config pc,size_t len) { BODY }
int main(int argc,char**) {
  if(argc>1) {
    puts("// Generated by generate_companion_table.py --vectors from pinned SX126x::calculateTimeOnAir.");
    puts("#pragma once\n#include <stdint.h>\nstruct LoRaReferenceProfile { const char* name; uint32_t airtime[256]; };\nstatic const LoRaReferenceProfile LORA_REFERENCE[] = {");
    struct Settings { const char* name; uint8_t sf; float bw; uint8_t cr; uint16_t pre; bool crc,implicit; };
    Settings settings[]={{"AU SF7 BW62.5 CR7",7,62.5,7,32,true,false},
      {"SF8 BW62.5 CR5",8,62.5,5,32,true,false},{"SF9 BW62.5 CR7",9,62.5,7,16,true,false},
      {"SF11 BW62.5 CR7",11,62.5,7,16,true,false},{"SF12 BW62.5 CR7",12,62.5,7,16,true,false},
      {"SF7 BW125 CR5",7,125,5,32,true,false},{"SF7 short preamble no CRC",7,62.5,5,16,false,false},
      {"SF7 implicit header",7,62.5,7,32,true,true}};
    for(const auto& p:settings) {
      Data dr{{p.sf,p.bw,p.cr}}; Config pc{{(1000u<<p.sf)/p.bw>=16000,p.implicit,p.crc,p.pre}};
      printf("{\"%s\",{",p.name);
      for(int n=0;n<256;n++) printf("%s%u",n?",":"",reference(dr,pc,n)/1000);
      puts("}},");
    }
    puts("};"); return 0;
  }
  puts("| SF | BW | CR | Width | Route | Login RX ms | TRACE ms | Maximum s | Reserved probes | Capped |");
  puts("|---:|---:|---:|---:|:---|---:|---:|---:|---:|:---|");
  for(int sf : {7,8,9,11,12}) for(int width : {1,2}) for(int r : {1,2,4,10,0}) {
    Data dr{{uint8_t(sf),62.5f,7}};
    Config pc{{(1000u<<sf)/62.5f>=16000,false,true,uint16_t(sf<=8?32:16)}};
    auto air=[&](int bytes){return reference(dr,pc,bytes)/1000;};
    int count=r?r:10; uint32_t probe=air(11+(2*count-1)*(width+1));
    TraceTransactionBudget budget;
    bool valid=budget.calculate(true,true,r!=0,count,air(22),air(53),probe,air(185));
    char route[20]; if(r) snprintf(route,sizeof(route),"%d",r); else snprintf(route,sizeof(route),"unknown");
    printf("| %d | 62.5 | 7 | %d | %s | %u | %u | %u | %u | %s |\n",sf,width,route,
        budget.login_wait,TraceTimingPolicy::attemptTimeout(count,probe),valid?budget.seconds():0,
        budget.planned_probes,budget.capped?"yes":"no");
  }
}
'''.replace('BODY', body).replace('#include <cstdio>', '#include <cstdio>\n#include <initializer_list>')
with tempfile.TemporaryDirectory(prefix='meshcore-timing-') as folder:
    cpp = Path(folder)/'reference.cpp'
    binary = Path(folder)/'reference'
    cpp.write_text(program)
    subprocess.run(['g++','-std=c++17','-I'+str(root/'examples/bme680_sensor'),str(cpp),'-o',str(binary)],check=True)
    subprocess.run([str(binary)]+sys.argv[1:],check=True)
