// Original one-bit silhouettes grow from a sprout into leafy or winged forms.
// Ears, shoulders, feet and belly markings carry each branching lineage forward.
struct Form {
  const char* name;
  uint8_t size;
  const uint8_t* silhouette;
  uint8_t source_size;
  const uint8_t* preview;
  constexpr Form(const char* n,uint8_t s,const uint8_t* bits,uint8_t source=8,
                 const uint8_t* icon=nullptr)
      : name(n),size(s),silhouette(bits),source_size(source),preview(icon?icon:bits) {}
  bool pixel(uint8_t x,uint8_t y) const {
    return x<source_size && y<source_size &&
        (silhouette[y*(source_size/8)+x/8] & (1u<<(x%8)));
  }
};
