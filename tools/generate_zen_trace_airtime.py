"""Extract the installed, pinned RadioLib calculator verbatim for native tests."""
from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1]
source=(root/'.pio/libdeps/WioTrackerL1_Zen_OLED/RadioLib/src/modules/SX126x/SX126x.cpp').read_text()
start=source.index('    case RADIOLIB_MODEM_LORA: {',source.index('SX126x::calculateTimeOnAir'))
end=source.index('    case RADIOLIB_MODEM_FSK:',start)
body=source[start:end].removeprefix('    case RADIOLIB_MODEM_LORA: {')
body=body[:body.rfind('}')]
prefix='''// Generated by tools/generate_zen_trace_airtime.py; do not approximate the PHY formula.
#pragma once
#include <stdint.h>
#include <stddef.h>
struct ReferenceData { struct {uint8_t spreadingFactor;float bandwidth;uint8_t codingRate;} lora; };
struct ReferenceConfig { struct {bool ldrOptimize,implicitHeader,crcEnabled;uint16_t preambleLength;} lora; };
inline uint32_t referenceAirtime(ReferenceData dr,ReferenceConfig pc,size_t len) {
'''
out=prefix+body+'}\n// Calculator body SHA256: '+hashlib.sha256(body.encode()).hexdigest()+'\n'
(root/'test/test_trace_adaptations/TraceAirtimeReference.h').write_text(out)
